const { _electron: electron } = require('playwright-core');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const root = path.resolve(__dirname, '..');
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'potato-home-library-'));
  const music = path.join(home, 'music'); fs.mkdirSync(music);
  const shots = path.join(root, 'dist/review-home'); fs.mkdirSync(shots, { recursive: true });
  const wav = Buffer.alloc(44 + 160000); wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(8000, 24); wav.writeUInt32LE(16000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(160000, 40);
  const titles = ['微光', '远山', '雨后', '留白', '星河', '归途', '夏日回声', '深蓝'];
  titles.forEach((title, i) => fs.writeFileSync(path.join(music, `Artist ${i % 4} - ${title}.wav`), wav));
  const env = { ...process.env, POTATOMUSIC_HOME: home, POTATOMUSIC_LIBRARY: music, POTATOMUSIC_IMPORT_SUPER: '0', POTATO_HIDDEN: '1', POTATO_ALLOW_SECOND_INSTANCE: '1' }; delete env.ELECTRON_RUN_AS_NODE;
  let app;
  try {
    app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: root, env, timeout: 40000 });
    const page = await app.firstWindow(); const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.waitForSelector('.ai-home-library');
    const invoke = (method, params = {}) => page.evaluate(([m,p]) => window.potato.invoke(m,p), [method,params]);
    await invoke('playback.volume', { volume: 0 }); await invoke('playback.mute', { muted: true });
    assert.equal(await page.locator('.ai-home-module-empty').count(), 2, 'uncategorized/unplayed library has helpful empty states');
    const boot = await invoke('bootstrap');
    for (const [i, track] of boot.tracks.entries()) await invoke('library.patchMetadata', { trackId: track.id, patch: { block: ['日常收藏', '原声集', '夜间电台'][i % 3], genre: ['Ambient', 'Pop', 'Electronic', 'Soundtrack'][i % 4], rating: 8 + i / 4, playCount: i * 3, addedAt: 1000 + i } });
    await page.evaluate(() => { localStorage.setItem('potato:appearance:v1', JSON.stringify({ language: 'zh', style: 'editorial' })); localStorage.setItem('potato:theme', 'light'); });
    await page.reload(); await page.waitForSelector('.ai-home-repeat-row');
    await page.setViewportSize({ width: 1440, height: 960 });
    assert.equal(await page.locator('.ai-record-card').count(), 4, 'existing primary cards retained');
    assert.equal(await page.locator('.hero').count(), 0, 'old primary hero excluded');
    assert.equal(await page.locator('.ai-home-library section').count(), 5);
    assert.equal(await page.locator('.ai-home-block').count(), 3);
    assert.equal(await page.locator('.ai-home-repeat-row').count(), 6);
    assert.equal(await page.locator('.ai-home-record-shelf .media-card').count(), 8);
    assert.equal(await page.locator('.ai-home-artist').count(), 4);
    assert.match(await page.locator('.ai-home-repeat-row').first().innerText(), /21 次播放/);
    await page.screenshot({ path: path.join(shots, 'top.png') });
    await page.locator('.ai-library-overview').scrollIntoViewIfNeeded(); await page.waitForTimeout(350);
    await page.screenshot({ path: path.join(shots, 'library.png') });
    await page.locator('.ai-home-artist-shelf').scrollIntoViewIfNeeded(); await page.waitForTimeout(350);
    await page.screenshot({ path: path.join(shots, 'listening.png') });
    const favorite = page.locator('.ai-home-favorite').first(); await favorite.click(); assert.equal(await favorite.getAttribute('aria-pressed'), 'true');
    await page.locator('.ai-home-library').getByRole('button', { name: '播放全部', exact: true }).click();
    const state = await invoke('playback.state'); assert.equal(state.queue.length, 6);
    await invoke('playback.toggle');
    await page.locator('.ai-home-block').first().click(); await page.waitForSelector('.page--tag');
    await page.locator('.ai-sidebar button').filter({ hasText: /^(首页|Home)/ }).click(); await page.waitForSelector('.ai-home-library');
    await page.locator('.ai-home-artist-open').first().click(); await page.waitForSelector('.page--artist');
    await page.locator('.ai-sidebar button').filter({ hasText: /^(首页|Home)/ }).click(); await page.waitForSelector('.ai-home-library');
    await page.getByRole('button', { name: '切换主题', exact: true }).click();
    await page.locator('.ai-home-artist-shelf').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(shots, 'dark.png') });
    await page.setViewportSize({ width: 1120, height: 800 });
    await page.locator('.ai-home-taxonomy').scrollIntoViewIfNeeded();
    assert(await page.locator('.ai-home-library').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'modules do not overflow narrow pane');
    await page.screenshot({ path: path.join(shots, 'compact.png') });
    assert.deepEqual(errors, []);
    console.log('Home modules: main area preserved; empty states, rankings, favorites, playback queue, category/artist navigation, light/dark/narrow layouts passed.');
    console.log(`Screenshots: ${shots}`);
  } finally { if (app) await app.close(); fs.rmSync(home, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
